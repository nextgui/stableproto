package lockfile

// The mapping between a schema and the s-expressions a lock file holds.
//
// Separate from sexp.go on purpose: that file knows parentheses and this one
// knows fields, and neither has to reason about the other's failures. A
// malformed file is rejected by the reader before anything here runs, so every
// function below is looking at a well-formed tree and only has to decide
// whether it is the right shape.

import (
	"fmt"
	"strconv"
)

// header is what the lock file says about itself, to the person who opens it
// after a build failed and has never seen one before.
const header = `; Schema lock. Generated by stableproto.
;
; This file records what every stored field is called and what number carries
; it. Data written last year is read by this year's code, so those two facts
; are a published interface: the number is what the wire format reads, and the
; name is what a JSON export prints. Changing either silently changes what
; somebody's existing data decodes to.
;
; The build fails when the schema and this file disagree. If you added a field,
; regenerate the lock. If you renamed, renumbered, retyped or deleted one, the
; regenerate step will refuse, because those are the changes this file exists to
; stop. Reserve the number instead and add a new field beside it.
`

// render writes the lock file for a schema.
func render(pkg string, s *schema) string {
	forms := []node{list(atom("package"), atom(pkg))}
	for _, o := range sortOverrides(s.removed) {
		forms = append(forms, list(atom("override-removed"), atom(o.was), atom(o.kind), atom(o.reason)))
	}

	for _, name := range s.names() {
		if m, ok := s.messages[name]; ok {
			form := list(atom("message"), atom(m.name))
			byNumber := overridesByNumber(m.overrides)
			for _, n := range sortedNumbers(m.fields) {
				// The override sits immediately above the field it waived, which
				// is where a reader looking at that field will see it and where
				// the diff puts it beside the change.
				for _, o := range byNumber[n] {
					form.children = append(form.children, overrideNode(o))
				}
				form.children = append(form.children, fieldNode(m.fields[n]))
			}
			for _, o := range orphanOverrides(m.overrides, hasFieldNumber(m)) {
				form.children = append(form.children, overrideNode(o))
			}
			for _, r := range sortedSpans(m.reserved) {
				form.children = append(form.children, spanNode(r))
			}
			for _, n := range sortedNames(m.reservedNames) {
				form.children = append(form.children, list(atom("reserved-name"), atom(n)))
			}
			forms = append(forms, form)
			continue
		}
		e := s.enums[name]
		form := list(atom("enum"), atom(e.name))
		byNumber := overridesByNumber(e.overrides)
		for _, n := range sortedNumbers(e.values) {
			for _, o := range byNumber[n] {
				form.children = append(form.children, overrideNode(o))
			}
			form.children = append(form.children, list(atom("value"), atom(strconv.Itoa(int(n))), atom(e.values[n])))
		}
		for _, o := range orphanOverrides(e.overrides, hasValueNumber(e)) {
			form.children = append(form.children, overrideNode(o))
		}
		for _, r := range sortedSpans(e.reserved) {
			form.children = append(form.children, spanNode(r))
		}
		for _, n := range sortedNames(e.reservedNames) {
			form.children = append(form.children, list(atom("reserved-name"), atom(n)))
		}
		forms = append(forms, form)
	}

	return header + "\n" + printForms(forms)
}

// fieldNode renders one field.
//
//	(field 2 id optional string)
//	(field 4 state optional enum .example.sample.Thing.State)
//	(field 3 counts optional (map string int64))
//	(field 5 cash optional int64 (oneof payload))
func fieldNode(f *field) node {
	out := list(atom("field"), atom(strconv.Itoa(int(f.number))), atom(f.name), atom(f.label))
	if f.mapKey != "" {
		out.children = append(out.children, list(atom("map"), atom(f.mapKey), atom(f.mapValue)))
	} else {
		out.children = append(out.children, atom(f.kind))
		if f.typeName != "" {
			out.children = append(out.children, atom(f.typeName))
		}
	}
	if f.oneof != "" {
		out.children = append(out.children, list(atom("oneof"), atom(f.oneof)))
	}
	return out
}

// overrideNode renders one waived check.
//
//	(override 2 renamed accounts "nothing has ever written this schema")
func overrideNode(o override) node {
	return list(atom("override"), atom(strconv.Itoa(int(o.number))), atom(o.kind), atom(o.was), atom(o.reason))
}

func overridesByNumber(in []override) map[int32][]override {
	out := map[int32][]override{}
	for _, o := range sortOverrides(in) {
		out[o.number] = append(out[o.number], o)
	}
	return out
}

// orphanOverrides are those whose field or value is no longer present, which is
// what a waived deletion leaves behind. They go after the fields rather than
// being dropped, because dropping them would erase the record on the next
// regeneration.
func orphanOverrides(in []override, present func(int32) bool) []override {
	var out []override
	for _, o := range sortOverrides(in) {
		if !present(o.number) {
			out = append(out, o)
		}
	}
	return out
}

func hasFieldNumber(m *message) func(int32) bool {
	return func(n int32) bool { _, ok := m.fields[n]; return ok }
}

func hasValueNumber(e *enum) func(int32) bool {
	return func(n int32) bool { _, ok := e.values[n]; return ok }
}

func parseOverrideForm(form node) (override, error) {
	if form.size() != 5 {
		return override{}, fmt.Errorf("line %d: an override form is (override <number> <kind> <was> <reason>)", form.line)
	}
	n, err := number(form.at(1))
	if err != nil {
		return override{}, err
	}
	return override{number: n, kind: form.at(2).text, was: form.at(3).text, reason: form.at(4).text}, nil
}

func spanNode(s span) node {
	if s.from == s.to {
		return list(atom("reserved"), atom(strconv.Itoa(int(s.from))))
	}
	return list(atom("reserved"), atom(strconv.Itoa(int(s.from))), atom(strconv.Itoa(int(s.to))))
}

// parseLock reads a lock file back into a schema.
func parseLock(text string) (*schema, error) {
	forms, err := readForms(text)
	if err != nil {
		return nil, err
	}

	s := &schema{messages: map[string]*message{}, enums: map[string]*enum{}}
	for _, form := range forms {
		if !form.isList() || form.size() == 0 {
			return nil, fmt.Errorf("line %d: a top-level form must be a list", form.line)
		}
		switch form.head() {
		case "package":
			// Recorded for the reader, not compared against anything.
		case "override-removed":
			if form.size() != 4 {
				return nil, fmt.Errorf("line %d: an override-removed form is (override-removed <name> <kind> <reason>)", form.line)
			}
			s.removed = append(s.removed, override{was: form.at(1).text, kind: form.at(2).text, reason: form.at(3).text})
		case "message":
			m, err := parseMessageForm(form)
			if err != nil {
				return nil, err
			}
			s.messages[m.name] = m
		case "enum":
			e, err := parseEnumForm(form)
			if err != nil {
				return nil, err
			}
			s.enums[e.name] = e
		default:
			return nil, fmt.Errorf("line %d: unknown top-level form %q", form.line, form.head())
		}
	}
	return s, nil
}

func parseMessageForm(form node) (*message, error) {
	if form.size() < 2 || form.at(1).isList() {
		return nil, fmt.Errorf("line %d: a message form names one message", form.line)
	}
	out := &message{name: form.at(1).text, fields: map[int32]*field{}, reservedNames: map[string]bool{}}

	for _, child := range form.children[2:] {
		switch {
		case child.headIs("field"):
			f, err := parseFieldForm(child)
			if err != nil {
				return nil, err
			}
			out.fields[f.number] = f
		case child.headIs("reserved"):
			r, err := parseSpanForm(child)
			if err != nil {
				return nil, err
			}
			out.reserved = append(out.reserved, r)
		case child.headIs("reserved-name"):
			if child.size() != 2 {
				return nil, fmt.Errorf("line %d: a reserved-name form names one name", child.line)
			}
			out.reservedNames[child.at(1).text] = true
		case child.headIs("override"):
			o, err := parseOverrideForm(child)
			if err != nil {
				return nil, err
			}
			out.overrides = append(out.overrides, o)
		default:
			return nil, fmt.Errorf("line %d: unknown form inside message %s", child.line, out.name)
		}
	}
	return out, nil
}

func parseEnumForm(form node) (*enum, error) {
	if form.size() < 2 || form.at(1).isList() {
		return nil, fmt.Errorf("line %d: an enum form names one enum", form.line)
	}
	out := &enum{name: form.at(1).text, values: map[int32]string{}, reservedNames: map[string]bool{}}

	for _, child := range form.children[2:] {
		switch {
		case child.headIs("value"):
			if child.size() != 3 {
				return nil, fmt.Errorf("line %d: a value form is (value <number> <name>)", child.line)
			}
			n, err := number(child.at(1))
			if err != nil {
				return nil, err
			}
			out.values[n] = child.at(2).text
		case child.headIs("reserved"):
			r, err := parseSpanForm(child)
			if err != nil {
				return nil, err
			}
			out.reserved = append(out.reserved, r)
		case child.headIs("reserved-name"):
			if child.size() != 2 {
				return nil, fmt.Errorf("line %d: a reserved-name form names one name", child.line)
			}
			out.reservedNames[child.at(1).text] = true
		case child.headIs("override"):
			o, err := parseOverrideForm(child)
			if err != nil {
				return nil, err
			}
			out.overrides = append(out.overrides, o)
		default:
			return nil, fmt.Errorf("line %d: unknown form inside enum %s", child.line, out.name)
		}
	}
	return out, nil
}

func parseFieldForm(form node) (*field, error) {
	if form.size() < 5 {
		return nil, fmt.Errorf("line %d: a field form is (field <number> <name> <label> <type>)", form.line)
	}
	n, err := number(form.at(1))
	if err != nil {
		return nil, err
	}
	out := &field{number: n, name: form.at(2).text, label: form.at(3).text}

	rest := form.children[4:]
	switch {
	case rest[0].headIs("map"):
		if rest[0].size() != 3 {
			return nil, fmt.Errorf("line %d: a map form is (map <key> <value>)", rest[0].line)
		}
		out.mapKey, out.mapValue = rest[0].at(1).text, rest[0].at(2).text
		// The same composed spelling the descriptor reader produces, so a
		// schema read from either format compares equal.
		out.kind = fmt.Sprintf("map<%s,%s>", out.mapKey, out.mapValue)
		rest = rest[1:]
	case !rest[0].isList():
		out.kind = rest[0].text
		rest = rest[1:]
		if len(rest) > 0 && !rest[0].isList() {
			out.typeName = rest[0].text
			rest = rest[1:]
		}
	default:
		return nil, fmt.Errorf("line %d: field %s has no type", form.line, out.name)
	}

	for _, extra := range rest {
		if !extra.headIs("oneof") || extra.size() != 2 {
			return nil, fmt.Errorf("line %d: unknown form in field %s", extra.line, out.name)
		}
		out.oneof = extra.at(1).text
	}
	return out, nil
}

func parseSpanForm(form node) (span, error) {
	from, err := number(form.at(1))
	if err != nil {
		return span{}, err
	}
	switch form.size() {
	case 2:
		return span{from: from, to: from}, nil
	case 3:
		to, err := number(form.at(2))
		if err != nil {
			return span{}, err
		}
		return span{from: from, to: to}, nil
	default:
		return span{}, fmt.Errorf("line %d: a reserved form is (reserved <n>) or (reserved <from> <to>)", form.line)
	}
}

func number(n node) (int32, error) {
	if n.isList() {
		return 0, fmt.Errorf("line %d: expected a number, found a list", n.line)
	}
	v, err := strconv.ParseInt(n.text, 10, 32)
	if err != nil {
		return 0, fmt.Errorf("line %d: %q is not a number", n.line, n.text)
	}
	return int32(v), nil
}
